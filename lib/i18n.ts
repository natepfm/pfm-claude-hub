// Lightweight locale layer (2026-08-24, Sam's ask: EN / RU / UK switch next to the
// theme toggle). No route changes, no middleware: the locale lives in a cookie
// (`pfm_lang`), the Nav sets it client-side and refreshes, server pages read it
// via getLocale() in lib/locale-server.ts (kept separate — next/headers cannot be
// imported from client components, and this dictionary module is client-safe).
// UI chrome + page prose are translated; skill catalog ROW DATA (names,
// descriptions, registry text) stays English on purpose — it is canonical
// tooling text that changes weekly and would rot in translation.

export type Locale = "en" | "ru" | "uk";
export const LOCALES: Locale[] = ["en", "ru", "uk"];
export const LANG_COOKIE = "pfm_lang";

export function isLocale(v: string | undefined | null): v is Locale {
  return v === "en" || v === "ru" || v === "uk";
}

